#!/usr/bin/env node
/**
 * Writes src/s3/fold-table.ts from the file the validator-side program wrote (test/fixtures/s3/go-written/fold-orbits.json, produced by
 * `xtsgen fold` from Go's unicode.SimpleFold): the runes encoding/json folds together when it matches a key to a field, each with the
 * smallest rune of its fold set. Nothing in the table is typed by hand.
 *
 *   node tools/gen-fold-table.mjs [test/fixtures/s3/go-written/fold-orbits.json]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2] ?? join(root, 'test/fixtures/s3/go-written/fold-orbits.json');
const raw = readFileSync(src);
const f = JSON.parse(raw.toString('utf8'));
if (f.format !== 'certen-sdk/s3-fold-orbits/v1' || !Array.isArray(f.folded) || f.folded.length === 0) {
  console.error('not a fold-orbits file');
  process.exit(2);
}
const flat = f.folded.flat();
const lines = [];
for (let i = 0; i < flat.length; i += 16) lines.push('  ' + flat.slice(i, i + 16).join(', ') + ',');
const out = `// GENERATED by tools/gen-fold-table.mjs from test/fixtures/s3/go-written/fold-orbits.json (xtsgen fold, ${f.go}, Unicode ${f.unicode}); do not edit.
// source sha256 ${createHash('sha256').update(raw).digest('hex')}
//
// Pairs [rune, smallest rune of its fold set] for every rune that has a fold set other than itself: what encoding/json's foldName makes of a
// key before it compares it with a field name.
export const FOLD_SOURCE = { go: ${JSON.stringify(f.go)}, unicode: ${JSON.stringify(f.unicode)}, runes: ${f.folded.length} } as const;
export const FOLD_PAIRS: readonly number[] = [
${lines.join('\n')}
];
`;
writeFileSync(join(root, 'src/s3/fold-table.ts'), out);
console.log(`src/s3/fold-table.ts: ${f.folded.length} runes (${f.go}, Unicode ${f.unicode})`);
