#!/usr/bin/env node
/**
 * Writes src/s3/certify-names.ts from the Go-written names file (validator pkg/proof/v2/testdata/certify1/names.json, a byte-identical copy
 * in test/fixtures/s3-f5/certify1) so the refusal and state names of the anchored certify form cannot drift between the two verifiers.
 *
 *   node tools/gen-certify-names.mjs            writes src/s3/certify-names.ts
 *   node tools/gen-certify-names.mjs --check    exits 1 when the checked-in file is not what the names file generates
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const namesPath = join(here, '..', 'test', 'fixtures', 's3-f5', 'certify1', 'names.json');
const outPath = join(here, '..', 'src', 's3', 'certify-names.ts');
const raw = readFileSync(namesPath);
const names = JSON.parse(raw.toString('utf8'));
if (names.format !== 'certen-certify1-names/1') throw new Error(`unknown names format ${names.format}`);
const camel = (s) => s.split('_').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const q = (s) => JSON.stringify(s);

let out = `/**
 * GENERATED by tools/gen-certify-names.mjs from testdata/certify1/names.json (validator pkg/proof/v2, sha256 below). Do not edit: the names,
 * their fields and their fixed detail text are the Go verifier's (certify_names.go), and test/certify1.test.ts fails when this file and the
 * names file disagree.
 */
export const CERTIFY_NAMES_SHA256 = ${q(createHash('sha256').update(raw).digest('hex'))};

/** The verifier's refusals and the builder's states (RB9-F5 section 3). */
export const CertifyCode = {
${names.names.map((n) => `  ${camel(n.name)}: ${q(n.name)},`).join('\n')}
} as const;

export type CertifyCodeName = (typeof CertifyCode)[keyof typeof CertifyCode];

/** The fields each code carries, in the order they are rendered. */
export const CERTIFY_FIELDS: Readonly<Record<string, readonly string[]>> = {
${names.names.map((n) => `  ${q(n.name)}: [${n.fields.map(q).join(', ')}],`).join('\n')}
};

/** The side that produces each code. */
export const CERTIFY_SIDE: Readonly<Record<string, 'verifier' | 'builder'>> = {
${names.names.map((n) => `  ${q(n.name)}: ${q(n.side)},`).join('\n')}
};

/** The fixed text after a code and its fields. */
export const CERTIFY_DETAILS: Readonly<Record<string, string>> = {
${names.names.map((n) => `  ${q(n.name)}: ${q(n.detail)},`).join('\n')}
};
`;
if (process.argv.includes('--check')) {
  const have = readFileSync(outPath, 'utf8');
  if (have !== out) {
    console.error('src/s3/certify-names.ts is not what testdata/certify1/names.json generates');
    process.exit(1);
  }
  console.log('certify-names.ts is current');
} else {
  writeFileSync(outPath, out);
  console.log(`wrote ${outPath}`);
}
