#!/usr/bin/env node
/**
 * Writes src/proof-v2/finality/adiri/genesis-link-data.ts: the base64 of the Adiri genesis link file (the 290 headers of blocks 1..290,
 * 176,758 B), which genesislink.ts imports dynamically. The source is the Go-published file (validator pkg/finality/adiri/testdata/pins/
 * genesis_link_1_290.bin, byte-identical to test/fixtures/finality/adiri4/link/genesis_link_1_290.bin); units_genesislink.test.ts fails if
 * the generated module is not that file. Usage, from packages/verify: node tools/gen-adiri-genesis-link.mjs [path-to-link.bin]
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2] ?? join(root, 'test', 'fixtures', 'finality', 'adiri4', 'link', 'genesis_link_1_290.bin');
const bytes = readFileSync(src);
const sha = createHash('sha256').update(bytes).digest('hex');
const body = `// GENERATED by tools/gen-adiri-genesis-link.mjs. Do not edit: test/finality/adiri/units_genesislink.test.ts fails if this is not the
// Go-published Adiri genesis link (validator pkg/finality/adiri/testdata/pins/genesis_link_1_290.bin).
// ${bytes.length} bytes, sha256 ${sha}. Imported dynamically by genesislink.ts, never from a barrel.
export const GENESIS_LINK_LENGTH = ${bytes.length};
export const GENESIS_LINK_SHA256 = '${sha}';
export const GENESIS_LINK_BASE64 =
  '${bytes.toString('base64')}';
`;
writeFileSync(join(root, 'src', 'proof-v2', 'finality', 'adiri', 'genesis-link-data.ts'), body);
console.log(`${bytes.length} bytes, sha256 ${sha}, module ${body.length} bytes`);
