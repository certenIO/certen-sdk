#!/usr/bin/env node
/**
 * Generates src/s3/enum-names.ts from Accumulate's own enum tables: for every enum type the proof's JSON carries as a name, the exact set
 * of names Go's <Type>ByName accepts (strings.ToLower of the name, aliases included) and the value each maps to.
 *
 *   node tools/gen-enum-names.mjs <accumulate-checkout> <commit>
 *
 * The checkout is the Accumulate module at the commit Kermit runs (e1d1db9ebb7c). Reading the Go source, not typing the names, is the
 * point: a name Go accepts that this table lacks would be a document Go verifies and this verifier refuses.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const [, , root, commit] = process.argv;
if (!root || !commit) {
  console.error('usage: node tools/gen-enum-names.mjs <accumulate-checkout> <commit>');
  process.exit(2);
}
const FILES = [
  ['protocol/enums_gen.go', ['AccountAuthOperationType', 'AccountType', 'AllowedTransactionBit', 'BookType', 'DataEntryType', 'ExecutorVersion', 'HashAlgorithm', 'KeyPageOperationType', 'NetworkMaintenanceOperationType', 'SignatureType', 'TransactionType', 'VoteType', 'PartitionType']],
  ['pkg/types/messaging/enums_gen.go', ['MessageType']],
];

const out = {};
for (const [file, types] of FILES) {
  const src = readFileSync(join(root, file), 'utf8');
  const consts = new Map();
  for (const m of src.matchAll(/^const (\w+) (\w+) = (0x[0-9a-fA-F]+|\d+)\s*$/gm)) consts.set(m[1], Number(m[3]));
  for (const t of types) {
    const fn = src.match(new RegExp(`func ${t}ByName\\(name string\\) \\(${t}, bool\\) \\{\\n\\tswitch strings\\.ToLower\\(name\\) \\{\\n([\\s\\S]*?)\\n\\t\\}\\n\\treturn 0, false`));
    if (!fn) throw new Error(`${file}: no ${t}ByName`);
    const names = {};
    for (const m of fn[1].matchAll(/\tcase "([^"]*)":\n\t\treturn (\w+), true/g)) {
      if (!consts.has(m[2])) throw new Error(`${t}: constant ${m[2]} has no value`);
      names[m[1]] = consts.get(m[2]);
    }
    if (Object.keys(names).length === 0) throw new Error(`${t}: no names`);
    out[t] = names;
  }
}

const here = dirname(fileURLToPath(import.meta.url));
const body = Object.entries(out)
  .map(([t, names]) => `  ${t}: { ${Object.entries(names).map(([n, v]) => `${JSON.stringify(n)}: ${v}`).join(', ')} },`)
  .join('\n');
writeFileSync(
  join(here, '..', 'src', 's3', 'enum-names.ts'),
  `// DO NOT EDIT. Generated by tools/gen-enum-names.mjs from gitlab.com/accumulatenetwork/accumulate@${commit}
// (protocol/enums_gen.go, pkg/types/messaging/enums_gen.go): for every enum the proof's JSON carries as a name, the names Go's <Type>ByName
// accepts - lower case, aliases included - and the value each maps to.

/** Enum type -> lower-case name -> value. */
export const ENUM_NAMES: Readonly<Record<string, Readonly<Record<string, number>>>> = {
${body}
};

/** The value Go's <Type>ByName gives a JSON name, or undefined where it is not a name (strings.ToLower first, as Go does). */
export function enumByName(type: string, name: string): number | undefined {
  const t = ENUM_NAMES[type];
  if (!t) throw new Error(\`no enum table for \${type}\`);
  const k = name.toLowerCase();
  return Object.prototype.hasOwnProperty.call(t, k) ? t[k] : undefined;
}
`,
);
console.log(`wrote ${Object.keys(out).length} enum tables`);
