// Generates the two source files of src/proof-v2/identity that are copies of validator data:
//   names.ts     the constants of pkg/contractidentity/names_gen.go (the codes, rows, parts and tokens of the S8 registry), same identifiers
//   embedded.ts  states.json, vocab.json and the pinned identity manifest as text constants, with their sha256
// usage: node tools/gen-identity-embedded.mjs <path to pkg/contractidentity/names_gen.go>
// The embedded texts are read from test/fixtures/identity (byte-identical copies of the validator's testdata); test/identity/embedded.test.ts
// fails if a constant ever differs from them.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, '..');
const out = join(pkg, 'src', 'proof-v2', 'identity');
const fx = join(pkg, 'test', 'fixtures', 'identity');
const sha = (b) => createHash('sha256').update(b).digest('hex');

const goPath = process.argv[2];
if (!goPath) throw new Error('usage: node tools/gen-identity-embedded.mjs <names_gen.go>');
const go = readFileSync(goPath, 'utf8');
const lines = [];
for (const m of go.matchAll(/^\s*(\w+)\s*=\s*"((?:[^"\\]|\\.)*)"\s*(?:\/\/.*)?$/gm)) lines.push(`export const ${m[1]} = ${JSON.stringify(JSON.parse(`"${m[2]}"`))};`);
writeFileSync(
  join(out, 'names.ts'),
  `// GENERATED by tools/gen-identity-embedded.mjs from pkg/contractidentity/names_gen.go (sha256 ${sha(readFileSync(goPath))}); do not edit.\n${lines.join('\n')}\n`,
);

const texts = {
  STATES_JSON: readFileSync(join(fx, 'states.json'), 'utf8'),
  VOCAB_JSON: readFileSync(join(fx, 'vocab.json'), 'utf8'),
  MANIFEST_JSON: readFileSync(join(fx, 'manifest', 'identity-manifest.json'), 'utf8'),
};
let body = '// GENERATED by tools/gen-identity-embedded.mjs from the byte-identical copies in test/fixtures/identity; do not edit.\n';
for (const [k, v] of Object.entries(texts)) {
  body += `export const ${k} = ${JSON.stringify(v)};\n`;
  body += `export const ${k.replace('_JSON', '_SHA256')} = '${sha(readFileSync(join(fx, k === 'MANIFEST_JSON' ? 'manifest/identity-manifest.json' : k === 'STATES_JSON' ? 'states.json' : 'vocab.json')))}';\n`;
}
writeFileSync(join(out, 'embedded.ts'), body);
console.log(`names: ${lines.length} constants; embedded: ${Object.keys(texts).join(', ')}`);
